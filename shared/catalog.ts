const text = (key: string, label: string, required = false): Field => ({
  key,
  label,
  required,
  type: "string",
})
const longText = (key: string, label: string, required = false): Field => ({
  key,
  label,
  required,
  type: "text",
})
const number = (key: string, label: string, required = false): Field => ({
  key,
  label,
  required,
  type: "number",
})
const bool = (key: string, label: string, required = false): Field => ({
  key,
  label,
  required,
  type: "boolean",
})
const dropdown = (
  key: string,
  label: string,
  dynamic: string,
  required = false
): Field => ({
  dynamic,
  key,
  label,
  required,
  type: "string",
})
const multiDropdown = (
  key: string,
  label: string,
  dynamic: string,
  required = false
): Field => ({
  ...dropdown(key, label, dynamic, required),
  list: true,
})
const listText = (key: string, label: string, required = false): Field => ({
  ...text(key, label, required),
  list: true,
})
